#!/usr/bin/env node
// Extracts the embedded `const DATA={...}` JSON from the run-results dashboard and writes a
// normalized results file for the site: camelCase keys, every error rate as a fraction (0–1),
// numeric strings parsed, and server-identifying fields (paths, disk, kernel) left out.
//
// Usage: node scripts/extract-results.mjs <dashboard.html> <out.json>
import { readFileSync, writeFileSync } from 'node:fs'
import { basename } from 'node:path'

const [, , input, output] = process.argv
if (!input || !output) {
  console.error('Usage: node scripts/extract-results.mjs <dashboard.html> <out.json>')
  process.exit(1)
}

const html = readFileSync(input, 'utf8')
const match = html.match(/const DATA=(\{.*?\});\s*\n/s)
if (!match) {
  console.error(`Could not find "const DATA={...};" in ${input}`)
  process.exit(1)
}
const d = JSON.parse(match[1])

const split = (s) => ({
  werNormalized: s.wer_normalized,
  werRaw: s.wer_raw,
  cerNormalized: s.cer_normalized,
  utterances: s.num_utterances,
})

const results = {
  _meta: { source: basename(input), note: 'Generated by scripts/extract-results.mjs — do not edit by hand.' },
  summary: {
    model: d.summary.model,
    dataset: d.summary.dataset,
    modelRevision: d.summary.modelRevision,
    datasetRevision: d.summary.datasetRevision,
    checkpoint: d.summary.checkpoint,
    validation: split(d.summary.validation),
    test: split(d.summary.test),
    runStart: d.summary.runStart,
    runEnd: d.summary.runEnd,
    runSpan: d.summary.runSpan,
    trainRuntimeHours: d.summary.trainRuntimeHours,
  },
  // Greedy-decoding validation metrics at each evaluation step.
  training: d.metrics.map((m) => ({
    step: m.step,
    epoch: m.epoch,
    evalLoss: m.eval_loss,
    werNormalized: m.eval_wer_norm,
    werRaw: m.eval_wer_raw,
    cerNormalized: m.eval_cer_norm,
  })),
  // 5-beam validation metrics for the finalist checkpoints.
  reranking: d.reranking.map((r) => ({
    checkpoint: r.checkpoint,
    werNormalized: r.wer,
    werRaw: r.raw,
    cerNormalized: r.cer,
  })),
  regions: d.regions.map((r) => ({ region: r.name, wer: r.wer / 100, utterances: r.n })),
  provinces: d.provinces.map((p) => ({ id: p.name, region: p.region, wer: p.wer / 100, utterances: p.n })),
  distribution: {
    labels: d.distribution.labels,
    counts: d.distribution.counts,
    median: d.distribution.median,
    p90: d.distribution.p90,
    perfectRate: d.distribution.perfectRate,
    highRate: d.distribution.highRate,
    meanUtterance: d.distribution.meanUtterance,
    utterances: d.distribution.n,
  },
  examples: d.examples.map((e) => ({
    file: e.filename,
    region: e.region,
    province: e.province_name,
    durationSec: Number(e.duration),
    wer: Number(e.wer_norm),
    reference: e.reference,
    prediction: e.prediction,
  })),
  splits: d.splits.map((s) => ({
    name: s.name,
    utterances: s.num_utterances,
    hours: s.hours,
    minDurationSec: s.min_duration_s,
    maxDurationSec: s.max_duration_s,
    over30s: s.num_utterances_over_30s_truncated_by_whisper,
    speakers: s.num_speakers,
    provinces: s.num_provinces,
  })),
  trainingSetup: {
    trainUtterancesUsed: d.training.num_train_utterances_used,
    trainUtterancesDropped: d.training.num_train_utterances_dropped,
    perDeviceBatchSize: d.training.per_device_train_batch_size,
    gradientAccumulationSteps: d.training.gradient_accumulation_steps,
    effectiveBatchSize: d.training.effective_batch_size,
    generationMaxLength: d.training.final_generation_max_length,
  },
  recipe: {
    language: d.recipe.language,
    task: d.recipe.task,
    expandNumbers: d.recipe.expand_numbers,
    learningRate: d.recipe.learning_rate,
    lrScheduler: d.recipe.lr_scheduler_type,
    warmupSteps: d.recipe.warmup_steps,
    maxEpochs: d.recipe.num_train_epochs,
    effectiveBatchSize: d.recipe.effective_batch_size,
    weightDecay: d.recipe.weight_decay,
    maxGradNorm: d.recipe.max_grad_norm,
    specAugment: d.recipe.apply_spec_augment,
    maskTimeProb: d.recipe.mask_time_prob,
    maskTimeLength: d.recipe.mask_time_length,
    evalSteps: d.recipe.eval_steps,
    earlyStoppingPatience: d.recipe.early_stopping_patience,
    finalBeams: d.recipe.final_num_beams,
    maxLabelTokens: d.recipe.max_label_tokens,
    seed: d.recipe.seed,
  },
  // Only hardware/software versions — no paths, hostnames, disk or kernel strings.
  environment: {
    python: d.environment.python,
    torch: d.environment.torch,
    transformers: d.environment.transformers,
    cuda: d.environment.cuda,
    cudnn: d.environment.cudnn,
    gpu: d.environment.gpu,
    gpuVramGb: d.environment.gpu_total_vram_gb,
    bf16: d.environment.bf16_supported,
    tf32: d.environment.tf32_available,
    computeCapability: d.environment.compute_capability,
  },
  normalization: {
    raw: d.normalization.raw_wer,
    // NFC-normalize: the dashboard source uses NFD (combining marks) for Vietnamese samples,
    // but the site's copy.{vi,en}.ts rule keys are precomposed NFC — keep them in sync so the
    // `n.rules[rule]` lookup in Dataset.tsx doesn't silently miss.
    normalized: d.normalization.normalized_wer.map((rule) => rule.normalize('NFC')),
  },
}

writeFileSync(output, JSON.stringify(results, null, 2) + '\n')
console.log(`Wrote ${output}: ${results.provinces.length} provinces, ${results.examples.length} examples`)
